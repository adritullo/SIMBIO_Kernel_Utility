class _ListThread(QThread):
    ok = Signal(object, str)  # list[RemoteMk], method
    failed = Signal(str)

    def __init__(self, url: str) -> None:
        super().__init__()
        self.url = url

    def run(self) -> None:
        try:
            items, method = mkindex.list_metakernels(self.url)
            self.ok.emit(items, method)
        except UtilityError as exc:
            self.failed.emit(str(exc))
        except Exception as exc:
            self.failed.emit(f"Unexpected error: {exc}")


class _GetThread(QThread):
    progress = Signal(int, int, str, int, int)  # index, count, name, done bytes, total bytes
    ok = Signal(list)  # local paths
    failed = Signal(str)

    def __init__(self, items: list, dest: str) -> None:
        super().__init__()
        self.items, self.dest = items, dest
        self._cancel = False

    def cancel(self) -> None:
        self._cancel = True

    def run(self) -> None:
        paths = []
        try:
            for i, mk in enumerate(self.items, 1):
                p = mkindex.fetch(mk, self.dest, cancel=lambda: self._cancel,
                                  progress=lambda d, t, i=i, n=mk.name: self.progress.emit(i, len(self.items), n, d, t))
                paths.append(p)
            self.ok.emit(paths)
        except UtilityError as exc:
            self.failed.emit(str(exc))
        except Exception as exc:
            self.failed.emit(f"Unexpected error: {exc}")


class SearchCard(Card):
    title = "Search Kernel"
    subtitle = "List the metakernels (*.tm) published on the ESA SPICE server and download them"
    glyph = "⌕"
    needs_kernels = False

    COLS = ("Metakernel", "Type", "Modified", "Size")

    def build(self, root: QWidget) -> None:
        self.use_metakernel = lambda path: None  # wired by the main window: set it in the top bar and load/check it
        self._items: list[mkindex.RemoteMk] = []
        self._list_thread: _ListThread | None = None
        self._get_thread: _GetThread | None = None
        self._open_after = False

        outer = QHBoxLayout(root)
        outer.setContentsMargins(28, 24, 28, 24)
        outer.setSpacing(16)

        # ---------------- inputs ----------------
        left = Panel("Server folder")
        left.setFixedWidth(420)
        left.body.addWidget(label("Folder URL", "muted"))
        self.url = QLineEdit(str(self.config.get("sk_url", "") or mkindex.DEFAULT_URL))
        self.url.setProperty("mono", True)
        self.url.setToolTip(f"Folder that contains the metakernels. Default: {mkindex.DEFAULT_URL}\n"
                            "Clear the field to restore the default. http(s):// and ftp:// addresses work.")
        left.body.addWidget(self.url)
        self.btn_search = QPushButton("Search")
        self.btn_search.setProperty("primary", True)
        left.body.addWidget(self.btn_search)

        left.body.addSpacing(6)
        left.body.addWidget(label("Filter", "muted"))
        self.filter = QLineEdit()
        self.filter.setPlaceholderText("e.g. plan, v433, 2026-09")
        self.filter.setClearButtonEnabled(True)
        left.body.addWidget(self.filter)

        left.body.addWidget(label("Save metakernels to", "muted"))
        row = QHBoxLayout()
        self.dest = QLineEdit(str(self.config.get("sk_save_dir", "")) or self._default_dest())
        self.dest.setProperty("mono", True)
        self.dest.setPlaceholderText(f"{example_out_dir()}/{DEFAULT_REMOTE_ROOT}/mk")
        self.dest.setToolTip("Folder for the downloaded .tm files. The ESA layout (…/kernels/mk) lets the metakernel's relative "
                             "PATH_VALUES ('..') point at the kernels that the Kernel Download card then fetches.")
        bb = QPushButton("…")
        bb.setFixedWidth(40)
        bb.setStyleSheet("padding: 8px 0;")
        row.addWidget(self.dest, 1)
        row.addWidget(bb)
        left.body.addLayout(row)

        left.body.addSpacing(8)
        self.btn_dl = QPushButton("Download selected")
        self.btn_dl.setEnabled(False)
        self.btn_open = QPushButton("Download and use as metakernel")
        self.btn_open.setProperty("primary", True)
        self.btn_open.setEnabled(False)
        self.btn_open.setToolTip("Downloads the selected metakernel, puts it in the metakernel bar and loads it. If its kernels are "
                                 "not on this computer you are taken to Kernel Download.")
        left.body.addWidget(self.btn_dl)
        left.body.addWidget(self.btn_open)
        self.status = label("", "small", wrap=True)
        left.body.addWidget(self.status)
        self.error = label("", "error", wrap=True)
        self.error.hide()
        left.body.addWidget(self.error)
        left.body.addStretch(1)
        outer.addWidget(left)

        # ---------------- results ----------------
        right = QWidget()
        col = QVBoxLayout(right)
        col.setContentsMargins(0, 0, 0, 0)
        col.setSpacing(14)
        panel = Panel("Available metakernels")
        self.count = label("Press Search to list the folder.", "small")
        panel.body.addWidget(self.count)
        self.table = QTableWidget(0, len(self.COLS))
        self.table.setHorizontalHeaderLabels(self.COLS)
        self.table.setSelectionBehavior(QAbstractItemView.SelectRows)
        self.table.setSelectionMode(QAbstractItemView.ExtendedSelection)
        self.table.setEditTriggers(QAbstractItemView.NoEditTriggers)
        self.table.verticalHeader().hide()
        self.table.setShowGrid(False)
        self.table.setAlternatingRowColors(False)
        hh = self.table.horizontalHeader()
        hh.setSectionResizeMode(0, QHeaderView.ResizeToContents)
        hh.setSectionResizeMode(1, QHeaderView.Stretch)
        hh.setSectionResizeMode(2, QHeaderView.ResizeToContents)
        hh.setSectionResizeMode(3, QHeaderView.ResizeToContents)
        panel.body.addWidget(self.table, 1)
        col.addWidget(panel, 1)

        about = Panel("About these files")
        txt = label(_ABOUT, wrap=True)
        txt.setTextFormat(Qt.RichText)
        about.body.addWidget(txt)
        col.addWidget(about)
        outer.addWidget(right, 1)

        # ---------------- wiring ----------------
        self.btn_search.clicked.connect(self.search)
        self.url.returnPressed.connect(self.search)
        self.url.editingFinished.connect(self._url_edited)
        self.filter.textChanged.connect(self._apply_filter)
        bb.clicked.connect(self._browse)
        self.dest.editingFinished.connect(lambda: self.config.set("sk_save_dir", self.dest.text().strip()))
        self.table.itemSelectionChanged.connect(self._selection_changed)
        self.table.itemDoubleClicked.connect(lambda *_: self.download(open_after=True))
        self.btn_dl.clicked.connect(lambda: self.download(open_after=False))
        self.btn_open.clicked.connect(lambda: self.download(open_after=True))

    # ------------------------------------------------------------------ helpers
    def _default_dest(self) -> str:
        out = str(self.config.get("dl_out_dir", "") or "").strip()
        return str(Path(out) / DEFAULT_REMOTE_ROOT / "mk") if out else ""

    def _url_edited(self) -> None:
        if not self.url.text().strip():
            self.url.setText(mkindex.DEFAULT_URL)
        self.config.set("sk_url", "" if self.url.text().strip() == mkindex.DEFAULT_URL else self.url.text().strip())

    def _browse(self) -> None:
        p = QFileDialog.getExistingDirectory(self, "Save metakernels to", self.dest.text().strip() or "")
        if p:
            self.dest.setText(p)
            self.config.set("sk_save_dir", p)

    def _show_error(self, msg: str) -> None:
        self.error.setText(msg)
        self.error.setVisible(bool(msg))

    def _busy(self) -> bool:
        return bool((self._list_thread and self._list_thread.isRunning()) or (self._get_thread and self._get_thread.isRunning()))

    def selected(self) -> list[mkindex.RemoteMk]:
        rows = sorted({i.row() for i in self.table.selectedItems()})
        return [self._items[self.table.item(r, 0).data(Qt.UserRole)] for r in rows if not self.table.isRowHidden(r)]

    def _selection_changed(self) -> None:
        sel = self.selected()
        busy = self._busy()
        self.btn_dl.setEnabled(bool(sel) and not busy)
        self.btn_open.setEnabled(len(sel) == 1 and not busy)
        self.btn_dl.setText(f"Download selected ({len(sel)})" if len(sel) > 1 else "Download selected")

    def _apply_filter(self) -> None:
        needle = self.filter.text().strip().lower()
        shown = 0
        for r in range(self.table.rowCount()):
            text = " ".join(self.table.item(r, c).text() for c in range(len(self.COLS))).lower()
            hide = bool(needle) and needle not in text
            self.table.setRowHidden(r, hide)
            shown += not hide
        if self._items:
            self.count.setText(f"{len(self._items)} metakernels" + (f" — {shown} match the filter" if needle else ""))
        self._selection_changed()

    # ------------------------------------------------------------------ search
    def search(self) -> None:
        if self._busy():
            return
        self._show_error("")
        try:
            url = mkindex.normalize_url(self.url.text())
        except UtilityError as exc:
            self._show_error(str(exc))
            return
        self.config.set("sk_url", "" if url == mkindex.DEFAULT_URL else url)
        self.btn_search.setEnabled(False)
        self.count.setText("Searching…")
        self.status.setText("")
        self._list_thread = _ListThread(url)
        self._list_thread.ok.connect(self._listed)
        self._list_thread.failed.connect(self._list_failed)
        self._list_thread.finished.connect(lambda: (self.btn_search.setEnabled(True), self._selection_changed()))
        self._list_thread.start()

    def _listed(self, items: list, method: str) -> None:
        self._items = items
        self.table.setRowCount(0)
        self.table.setRowCount(len(items))
        for r, m in enumerate(items):
            vals = (m.name, m.kind, m.modified[:10] or "—", _fmt_bytes(m.size) if m.size is not None else "—")
            for c, v in enumerate(vals):
                it = QTableWidgetItem(v)
                if c == 0:
                    it.setData(Qt.UserRole, r)
                    it.setToolTip(m.url)
                if c == 2 and m.modified:
                    it.setToolTip(m.modified)
                if c == 3:
                    it.setTextAlignment(Qt.AlignRight | Qt.AlignVCenter)
                self.table.setItem(r, c, it)
        self.status.setText(f"Listed over {method.upper()}.")
        self._apply_filter()

    def _list_failed(self, msg: str) -> None:
        self.count.setText("Could not list the folder.")
        self._show_error(msg)

    # ------------------------------------------------------------------ download
    def download(self, open_after: bool = False) -> None:
        if self._busy():
            return
        self._show_error("")
        sel = self.selected()
        if not sel:
            self._show_error("Select the metakernel to download in the list.")
            return
        if open_after:
            sel = sel[:1]
        dest = self.dest.text().strip() or self._default_dest()
        if not dest:
            self._show_error("Choose the folder to save the metakernels to.")
            return
        self.dest.setText(dest)
        self.config.set("sk_save_dir", dest)
        self._open_after = open_after
        self.btn_dl.setEnabled(False)
        self.btn_open.setEnabled(False)
        self._get_thread = _GetThread(sel, dest)
        self._get_thread.progress.connect(self._get_progress)
        self._get_thread.ok.connect(self._downloaded)
        self._get_thread.failed.connect(self._get_failed)
        self._get_thread.finished.connect(self._selection_changed)
        self._get_thread.start()

    def _get_progress(self, i: int, n: int, name: str, done: int, total: int) -> None:
        self.status.setText(f"Downloading {i}/{n}  {name}  {_fmt_bytes(done)}" + (f" / {_fmt_bytes(total)}" if total else ""))

    def _downloaded(self, paths: list) -> None:
        names = ", ".join(p.name for p in paths[:3]) + (" …" if len(paths) > 3 else "")
        self.status.setText(f"Saved {len(paths)} file(s) to {paths[0].parent}: {names}")
        if self._open_after and paths:
            self.use_metakernel(str(paths[0]))

    def _get_failed(self, msg: str) -> None:
        self.status.setText("")
        self._show_error(msg)

    def shutdown(self) -> None:
        for t in (self._list_thread, self._get_thread):
            if t is not None and t.isRunning():
                if hasattr(t, "cancel"):
                    t.cancel()
                t.wait(5000)
